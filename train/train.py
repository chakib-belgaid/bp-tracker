"""Train DigitNet on synthetic seven-segment digits; evaluate on real crops; export weights.

    uv run python train.py                 # generate (cached) data, train, export ../digitnet-weights.js
    uv run python train.py --n 200000 --epochs 20 --device cpu
"""
from __future__ import annotations

import argparse
import base64
import json
import random
import time
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import torch
from torch import nn

from common import CROP_H, CROP_W, HERE, NOT_DIGIT, NUM_CLASSES, DigitNet, load_real, pick_device, render, seed_all, to_tensor

GEN_VERSION = 2  # bump when the generator changes, to invalidate the cache


def _chunk(args):
    seed, n = args
    rng = random.Random(seed)
    # not-a-digit is 1 in 6 samples; digits uniform
    labels = [NOT_DIGIT if rng.random() < 1 / 6 else rng.randrange(10) for _ in range(n)]
    return np.stack([render(y, rng) for y in labels]), np.array(labels, dtype=np.int64)


def synth(n: int, seed: int) -> tuple[np.ndarray, np.ndarray]:
    path = HERE / "data" / f"synth_v{GEN_VERSION}_{n}_{seed}.npz"
    if path.exists():
        d = np.load(path)
        return d["x"], d["y"]
    t = time.time()
    chunks = [(seed * 100_003 + i, 2000) for i in range((n + 1999) // 2000)]
    with Pool() as pool:
        parts = pool.map(_chunk, chunks)
    x = np.concatenate([p[0] for p in parts])[:n]
    y = np.concatenate([p[1] for p in parts])[:n]
    path.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(path, x=x, y=y)
    print(f"generated {n} synthetic samples in {time.time() - t:.0f}s -> {path.name}")
    return x, y


@torch.no_grad()
def evaluate(model, x, y, device):
    model.eval()
    logits = model(to_tensor(x).to(device)).cpu()
    pred = logits.argmax(1).numpy()
    return (pred == y).mean(), pred


def export_js(model: DigitNet, path: Path, meta: dict):
    """Weights as base64 float32 per tensor, wrapped in a tiny JS file (works in browser + Node)."""
    tensors = {}
    for name, p in model.state_dict().items():
        a = p.detach().cpu().numpy().astype("<f4")
        tensors[name] = {"shape": list(a.shape), "data": base64.b64encode(a.tobytes()).decode()}
    payload = json.dumps({"meta": meta, "tensors": tensors})
    path.write_text(
        "// Generated by train/train.py - do not edit.\n"
        "(function (root) {\n"
        f"  const w = {payload};\n"
        "  if (typeof module !== 'undefined' && module.exports) module.exports = w;\n"
        "  else root.DigitNetWeights = w;\n"
        "})(typeof self !== 'undefined' ? self : this);\n"
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=150_000)
    ap.add_argument("--epochs", type=int, default=15)
    ap.add_argument("--batch", type=int, default=256)
    ap.add_argument("--lr", type=float, default=3e-3)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--device", default=None, help="cpu or mps (default: mps if available)")
    ap.add_argument("--out", default=str(HERE.parent / "digitnet-weights.js"))
    args = ap.parse_args()

    seed_all(args.seed)
    device = torch.device(args.device) if args.device else pick_device()
    xs, ys = synth(args.n, args.seed)
    dev_x, dev_y, _ = load_real("dev")
    print(f"synthetic {len(xs)}  real dev {len(dev_x)}  device {device}")

    model = DigitNet().to(device)
    n_params = sum(p.numel() for p in model.parameters())
    print(f"DigitNet: {n_params} parameters ({n_params * 4 / 1024:.1f} KB as float32)")
    opt = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=1e-4)
    steps = args.epochs * ((len(xs) + args.batch - 1) // args.batch)
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, max_lr=args.lr, total_steps=steps)
    loss_fn = nn.CrossEntropyLoss(label_smoothing=0.05)
    X, Y = to_tensor(xs), torch.from_numpy(ys)

    best = (-1.0, None)
    for epoch in range(args.epochs):
        model.train()
        t = time.time()
        perm = torch.randperm(len(X))
        total = 0.0
        for i in range(0, len(X), args.batch):
            idx = perm[i:i + args.batch]
            xb, yb = X[idx].to(device), Y[idx].to(device)
            # cheap on-the-fly augmentation: random contrast and a 1-pixel shift
            xb = xb * torch.empty(len(xb), 1, 1, 1, device=device).uniform_(0.6, 1.3)
            if random.random() < 0.5:
                xb = torch.roll(xb, shifts=(random.randint(-1, 1), random.randint(-1, 1)), dims=(2, 3))
            loss = loss_fn(model(xb.clamp(0, 1)), yb)
            opt.zero_grad()
            loss.backward()
            opt.step()
            sched.step()
            total += loss.item() * len(idx)
        acc, _ = evaluate(model, dev_x, dev_y, device)
        print(f"epoch {epoch + 1:2d}  loss {total / len(X):.4f}  real-dev acc {acc:.3f}  ({time.time() - t:.1f}s)")
        if acc >= best[0]:
            best = (acc, {k: v.detach().clone() for k, v in model.state_dict().items()})

    model.load_state_dict(best[1])
    model = model.cpu()
    test_x, test_y, test_meta = load_real("test")
    acc_dev, _ = evaluate(model, dev_x, dev_y, "cpu")
    acc_test, pred = evaluate(model, test_x, test_y, "cpu")
    print(f"\nbest checkpoint: real-dev {acc_dev:.3f}  real-test {acc_test:.3f} ({len(test_x)} digits)")
    wrong = [(m["source"], m["row"], m["label"], int(p)) for m, p, y in zip(test_meta, pred, test_y) if p != y]
    for w_ in wrong[:20]:
        print("  test miss:", w_)

    export_js(model, Path(args.out), {
        "classes": NUM_CLASSES, "not_digit": NOT_DIGIT, "crop": [CROP_W, CROP_H], "params": n_params,
        "real_dev_acc": round(float(acc_dev), 4), "real_test_acc": round(float(acc_test), 4),
        "train": {"synthetic": len(xs), "epochs": args.epochs, "gen_version": GEN_VERSION, "seed": args.seed},
    })
    print("weights written to", args.out)


if __name__ == "__main__":
    main()
